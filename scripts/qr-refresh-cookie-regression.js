"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const { buildRefreshCookie, buildClearRefreshCookie, readRefreshTokenCookie } = require('../lib/auth-session-store');
const { qrCookieName, selectedRefreshToken, sessionRefreshCookie, clearSelectedRefreshCookie } = require('../lib/qr-refresh-cookie');
const oldSid = 'a'.repeat(32), newSid = 'b'.repeat(32);
const oldToken = `rai_rt_v1.${oldSid}.${'x'.repeat(64)}`, newToken = `rai_rt_v1.${newSid}.${'y'.repeat(64)}`;
const options = { production: true, path: '/api/auth', ttlSeconds: 1234, sameSite: 'None' };
const store = { readRefreshTokenCookie, buildClearRefreshCookie: () => buildClearRefreshCookie(options) };
const original = buildRefreshCookie(oldToken, options);
const candidate = sessionRefreshCookie({ sessionId: newSid, refreshCookie: buildRefreshCookie(newToken, options) }, newSid);
assert.notEqual(candidate.name, original.name);
assert.match(candidate.header, /; Secure/); assert.match(candidate.header, /; HttpOnly/);
assert.match(candidate.header, /SameSite=None/); assert.match(candidate.header, /Max-Age=1234/);
const jar = `${original.name}=${oldToken}; ${candidate.name}=${newToken}`;
assert.equal(selectedRefreshToken(store, jar), oldToken, 'late QR cookie cannot replace ordinary login');
assert.equal(selectedRefreshToken(store, jar, newSid), newToken, 'accepted token explicitly selects its cookie');
assert.equal(selectedRefreshToken(store, `${original.name}=${oldToken}`, newSid), null, 'missing QR must not fall back to another account');
assert.equal(selectedRefreshToken(store, `${candidate.name}=${oldToken}`, newSid), null, 'cookie session must match selected scope');
assert.equal(selectedRefreshToken(store, `${jar}; ${candidate.name}=${newToken}`, newSid), null, 'duplicate named cookie fails closed');
assert.throws(() => selectedRefreshToken(store, jar, ''));
assert.throws(() => qrCookieName('../rai_refresh'));
assert.throws(() => sessionRefreshCookie({ sessionId: oldSid, refreshCookie: original }, newSid));
const cleared = clearSelectedRefreshCookie(store, newSid);
assert.equal(cleared.name, candidate.name); assert.match(cleared.header, /Max-Age=0/);
assert.match(cleared.header, /; Secure/); assert.match(cleared.header, /; HttpOnly/);
assert.equal(clearSelectedRefreshCookie(store).name, original.name);
// Execute the actual client selector, not a reimplementation. Malformed scoped
// tokens must fail closed, not silently refresh the legacy login.
const source = fs.readFileSync(path.join(__dirname, '../public/app.js'), 'utf8');
const start = source.indexOf('function getUserRefreshScopeHeaders(');
const end = source.indexOf('async function performUserAccessTokenRefresh(', start);
assert.ok(start >= 0 && end > start);
const context = { decodeUserAccessTokenPayload: token => token };
vm.runInNewContext(source.slice(start, end) + '\nthis.select = getUserRefreshScopeHeaders;', context);
assert.equal(Object.keys(context.select({ auth_method: 'password', sid: oldSid })).length, 0);
assert.equal(context.select({ auth_method: 'qr_browser', sid: newSid })['X-RAI-QR-Session'], newSid);
assert.equal(context.select({ auth_method: 'qr_browser', sid: '../bad' })['X-RAI-QR-Session'], 'invalid');
assert.match(source, /getUserRefreshScopeHeaders\(context\.token\)/);
console.log('QR refresh cookie PASS: isolated names, explicit selection, no fallback, scope match, duplicate rejection, flags/TTL preservation, scoped clearing, client selection');
