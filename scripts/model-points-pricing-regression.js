'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { CHAT_MODEL_IDS, CHAT_MODEL_LIMITS } = require('../lib/chat-model-policy');
const root = path.resolve(__dirname,'..');
const server = fs.readFileSync(path.join(root,'server.js'),'utf8');
const app = fs.readFileSync(path.join(root,'public/app.js'),'utf8');
assert.match(server,/CHAT_MODEL_IDS.includes\(model\).*return 0/,'conversation allowances must not double debit points');
assert.match(server,/'gpt-image-2': 20/,'existing image tool point cost is unrelated to chat quotas');
assert.match(server,/RAI_DEEPSEEK_FAST_API_KEY_FILE/);
assert.match(server,/DEEPSEEK_FAST_API_KEY \|\| ENV_API_KEYS.DEEPSEEK_API_KEY/);
assert.match(app,/renderMembershipModelPricing/);
assert.match(app,/shared account-wide|Web 与 CX RAI 共用额度/);
for(const id of CHAT_MODEL_IDS.filter(x=>x.startsWith('gpt')))assert.ok(CHAT_MODEL_LIMITS.free[id]>0);
assert.match(server,/pwaInstall: \{ key: 'pwa_install', points: 10 \}/);
assert.match(server,/inviteUser: \{ keyPrefix: 'invite_user:', points: 50 \}/);
assert.match(server,/bookmarkDomain: \{ key: 'bookmark_domain', points: 10 \}/);
console.log('model_points_pricing_regression_ok: chat allowances replace chat point costs; unrelated rewards/image pricing retained');
