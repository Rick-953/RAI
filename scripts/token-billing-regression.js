'use strict';
const assert = require('node:assert/strict');
const { normalize } = require('../public/token-billing');
const options = { provider: 'openai_official', model: 'gpt-6-luna', cacheTtl: '12h' };
const usage = { input_tokens: 12000, output_tokens: 50, input_tokens_details: { cached_tokens: 4000,
    cache_write_tokens: 7000, cache_write_tokens_details: { ttl_30m_tokens: 5000, ttl_12h_tokens: 2000 } } };
const mixed = normalize(usage, options);
assert.equal(mixed.inputTokens, 12000);
assert.equal(mixed.uncachedInputTokens, 1000, 'reads and writes are disjoint input billing buckets');
assert.equal(mixed.cacheHitRate, 1 / 3);
assert.equal(mixed.cacheReadTokens, 4000);
assert.equal(mixed.cacheWriteTokens, 7000);
assert.equal(mixed.requestedRetentionSeconds, 43200);
assert.equal(mixed.actualCacheAgeSeconds, null, 'retention request does not prove actual cache age');
assert.equal(mixed.estimatedUsd, 0.00129, 'ordinary input + output + cached reads + each write lifetime, charged once');
assert.deepEqual(mixed.costsUsd, { input: 0.0001, output: 0.000025, cacheRead: 0.00004, cacheWrite30m: 0.000625, cacheWrite12h: 0.0005 });
assert.equal(normalize(mixed).estimatedUsd, mixed.estimatedUsd, 'client upload normalization preserves the estimate');
const unknown = normalize({ input_tokens: 12000, output_tokens: 50 }, options);
for (const key of ['cacheReadTokens','cacheWriteTokens','cacheHit','cacheHitRate','estimatedUsd']) assert.equal(unknown[key], null);
assert.equal(normalize({ ...usage, input_tokens_details: { cached_tokens: 13000 } }, options).cacheReadTokens, null);
assert.equal(normalize({ ...usage, input_tokens_details: { cached_tokens: 6000, cache_write_tokens: 7000 } }, options).estimatedUsd, null);
assert.equal(normalize({ ...usage, input_tokens_details: { ...usage.input_tokens_details, cache_write_tokens: 6000 } }, options).cacheWrite30mTokens, null);
const thirdParty = normalize(usage, { provider: 'custom_api', model: 'gpt-6-luna' });
assert.equal(thirdParty.estimatedUsd, null, 'a relay model name cannot establish official pricing');
assert.equal(thirdParty.pricing, null);
assert.equal(normalize(usage, { provider:'custom_api', model:'gpt-6-luna', cacheTtl:'12h' }).requestedRetentionSeconds, null, 'OAI retention rules do not apply to third parties');
assert.equal(normalize(usage, { ...options, serviceTier: 'priority' }).estimatedUsd, null, 'unknown service tier has no invented rate');
const reported = normalize({ total_cost: 0.25, currency: 'USD' });
assert.equal(reported.reportedCost, 0.25); assert.equal(reported.estimatedUsd, null);
assert.equal(normalize({ input_tokens: 10, output_tokens: 2, cache_read_input_tokens: 20, cache_creation_input_tokens: 30 }).inputTokens, 60);
assert.equal(normalize({ prompt_tokens: 60, completion_tokens: 2, cache_read_input_tokens: 20, cache_creation_input_tokens: 30 }).inputTokens, 60);
assert.equal(JSON.stringify(normalize({ ...usage, text: 'PRIVATE-CANARY', cost: { token: 'PRIVATE-CANARY' } }, options)).includes('PRIVATE-CANARY'), false);
console.log('Token billing PASS: disjoint input/read/30m-write/12h-write/output costs, rates, unknowns, service tiers, retention provenance and privacy');
