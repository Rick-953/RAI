'use strict';
const assert = require('node:assert/strict');
const { createQrLoginStore } = require('../lib/qr-login');
let now = 1000000;
const store = createQrLoginStore({ now: () => now, maxEntries: 2 });
let session = store.create('Test browser');
assert.match(session.id, /^[A-Za-z0-9_-]{43}$/);
assert.notEqual(session.scanToken, session.ownerSecret);
assert.equal(session.rotateAfterMs, 3000);
assert.throws(() => store.poll(session.id, session.scanToken), /qr_not_found/);
const old = session.scanToken;
now += 3000;
assert.throws(() => store.claim(session.id, old, 1, 'session-a', 7), /qr_scan_expired/);
const rotated = store.poll(session.id, session.ownerSecret);
assert.notEqual(rotated.scanToken, old);
assert.throws(() => store.claim(session.id, old, 1, 'session-a', 7), /qr_scan_expired/);
const claim = store.claim(session.id, rotated.scanToken, 1, 'session-a', 7);
assert.equal(claim.code, session.code);
assert.equal(claim.ownerSecret, undefined);
assert.throws(() => store.claim(session.id, rotated.scanToken, 2, 'session-b', 7), /qr_scan_expired/);
assert.throws(() => store.consume(session.id, session.ownerSecret), /qr_not_approved/);
assert.throws(() => store.decide(session.id, claim.approvalSecret, 2, 'session-a', true), /qr_invalid_confirmation/);
assert.throws(() => store.decide(session.id, claim.approvalSecret, 1, 'session-b', true), /qr_invalid_confirmation/);
assert.throws(() => store.decide(session.id, 'wrong', 1, 'session-a', true), /qr_invalid_confirmation/);
store.decide(session.id, claim.approvalSecret, 1, 'session-a', true);
assert.deepEqual(store.consume(session.id, session.ownerSecret), { userId: 1, sessionId: 'session-a', sessionVersion: 7 });
assert.throws(() => store.consume(session.id, session.ownerSecret), /qr_expired/);
session = store.create('Test');
const denied = store.claim(session.id, session.scanToken, 1, 'a', 7);
store.decide(session.id, denied.approvalSecret, 1, 'a', false);
assert.throws(() => store.consume(session.id, session.ownerSecret), /qr_not_approved/);
store.cancel(session.id, session.ownerSecret);
assert.throws(() => store.poll(session.id, session.ownerSecret), /qr_expired/);
session = store.create('Expiry'); now += 120001;
assert.throws(() => store.poll(session.id, session.ownerSecret), /qr_expired/);
store.create('one');store.create('two');assert.throws(() => store.create('three'), /qr_busy/);
console.log('QR login regression PASS: rotation, expiry, owner isolation, explicit confirmation, session binding, replay, deny, cancel, bounded store');
